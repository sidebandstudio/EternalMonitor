//! USB keyboard page 0x07 to Windows Scan 1 make codes.
//! Reference: https://learn.microsoft.com/windows/win32/inputdev/about-keyboard-input#scan-codes
//! Windows represents Pause as 0x45 and Num Lock as extended 0x45 in
//! keyboard messages; this avoids confusing the two with SendInput.

/// Returns the scan byte and whether KEYEVENTF_EXTENDEDKEY is required.
pub fn hid_to_scancode(usage: u16) -> Option<(u16, bool)> {
    // Bit 8 records an E0 prefix, rather than emitting it as a separate key.
    const KEYS: [u16; 98] = [
        0x1e, 0x30, 0x2e, 0x20, 0x12, 0x21, 0x22, 0x23, 0x17, 0x24, 0x25, 0x26, 0x32, 0x31, 0x18,
        0x19, 0x10, 0x13, 0x1f, 0x14, 0x16, 0x2f, 0x11, 0x2d, 0x15, 0x2c, // A..Z
        0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, // 1..0
        0x1c, 0x01, 0x0e, 0x0f, 0x39, 0x0c, 0x0d, 0x1a, 0x1b, 0x2b, 0x2b, 0x27, 0x28, 0x29, 0x33,
        0x34, 0x35, 0x3a, // Enter..Caps Lock
        0x3b, 0x3c, 0x3d, 0x3e, 0x3f, 0x40, 0x41, 0x42, 0x43, 0x44, 0x57, 0x58, 0x137, 0x46,
        0x45, // Print Screen, Scroll Lock, Pause
        0x152, 0x147, 0x149, 0x153, 0x14f, 0x151, 0x14d, 0x14b, 0x150, 0x148, 0x145, 0x135, 0x37,
        0x4a, 0x4e, 0x11c, // Num Lock, keypad operators
        0x4f, 0x50, 0x51, 0x4b, 0x4c, 0x4d, 0x47, 0x48, 0x49, 0x52, 0x53, 0x56,
        0x15d, // Non-US backslash, Application
    ];
    const MODIFIERS: [u16; 8] = [0x1d, 0x2a, 0x38, 0x15b, 0x11d, 0x36, 0x138, 0x15c];
    let code = match usage {
        0x04..=0x65 => KEYS[(usage - 4) as usize],
        0xe0..=0xe7 => MODIFIERS[(usage - 0xe0) as usize],
        _ => return None,
    };
    Some((code & 0xff, code & 0x100 != 0))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_supported_usage_and_only_supported_usages_map() {
        for usage in 0..=u16::MAX {
            let code = hid_to_scancode(usage);
            assert_eq!(
                code.is_some(),
                (4..=0x65).contains(&usage) || (0xe0..=0xe7).contains(&usage)
            );
            if let Some((scan, _)) = code {
                assert!((1..=0x7f).contains(&scan));
            }
        }
        let extended: Vec<_> = (0..=0xe7)
            .filter(|&usage| hid_to_scancode(usage).is_some_and(|(_, e)| e))
            .collect();
        assert_eq!(
            extended,
            vec![
                0x46, 0x49, 0x4a, 0x4b, 0x4c, 0x4d, 0x4e, 0x4f, 0x50, 0x51, 0x52, 0x53, 0x54, 0x58,
                0x65, 0xe3, 0xe4, 0xe6, 0xe7
            ]
        );
    }

    #[test]
    fn physical_positions_and_keypad_are_distinct() {
        for (usage, scan, extended) in [
            (0x04, 0x1e, false),
            (0x14, 0x10, false),
            (0x1d, 0x2c, false),
            (0x28, 0x1c, false),
            (0x58, 0x1c, true),
            (0x48, 0x45, false),
            (0x53, 0x45, true),
            (0x54, 0x35, true),
            (0x38, 0x35, false),
            (0x50, 0x4b, true),
            (0x5c, 0x4b, false),
            (0xe0, 0x1d, false),
            (0xe4, 0x1d, true),
            (0xe5, 0x36, false),
            (0x65, 0x5d, true),
        ] {
            assert_eq!(hid_to_scancode(usage), Some((scan, extended)));
        }
    }
}
